const I18nContext = createContext<I18nContextType>({
  lang: "vi",
  setLang: () => {},
  toggleLang: () => {},
  t: (key: string, fallback?: string) => fallback || key,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    const saved = localStorage.getItem("tracescope_lang") as Language;
    return saved === "en" || saved === "vi" ? saved : "vi"; // Default to Vietnamese
  });

  const setLang = (newLang: Language) => {
    setLangState(newLang);
    localStorage.setItem("tracescope_lang", newLang);
  };

  const toggleLang = () => {
    setLang(lang === "vi" ? "en" : "vi");
  };

  const t = (key: string, fallback?: string): string => {
    if (lang === "en") {
      return translations.en[key] || key;
    }
    const dict = translations.vi;
    if (dict[key]) {
      return dict[key];
    }
    // Case-insensitive lookup fallback
    const lower = key.toLowerCase().trim();
    for (const [k, v] of Object.entries(dict)) {
      if (k.toLowerCase().trim() === lower) {
        return v;
      }
    }
    return fallback || key;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, toggleLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);

/**
 * Compact, modern language toggle component for the header
 */
export function LanguageSwitcher() {
  const { lang, toggleLang } = useI18n();

  return (
    <button
      type="button"
      onClick={toggleLang}
      title={lang === "vi" ? "Chuyển sang Tiếng Anh (Switch to English)" : "Switch to Vietnamese (Chuyển sang Tiếng Việt)"}
      className="flex items-center gap-1.5 rounded-lg border border-[#262838] bg-[#141622] px-2.5 py-1 text-xs font-bold text-white transition hover:border-cyan-400/60 hover:bg-[#1a1d2e] focus:outline-none"
    >
      <span className="text-sm leading-none">{lang === "vi" ? "🇻🇳" : "🇬🇧"}</span>
      <span className="font-mono text-[11px] font-bold uppercase tracking-wider text-cyan-300">
        {lang === "vi" ? "VI" : "EN"}
      </span>
    </button>
  );
}
