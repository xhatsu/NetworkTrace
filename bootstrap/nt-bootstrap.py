def run_server():
    ensure_bundle_tar()
    server_address = ("0.0.0.0", BOOTSTRAP_PORT)
    httpd = ThreadingHTTPServer(server_address, BootstrapHandler)
    print(f"[nt-bootstrap] Server listening on 0.0.0.0:{BOOTSTRAP_PORT} (Hub port: {HUB_PORT})", flush=True)
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        httpd.server_close()
        print("[nt-bootstrap] Server stopped.", flush=True)


if __name__ == "__main__":
    run_server()
