BASE_DIR = os.path.dirname(os.path.abspath(__file__))
PARENT_DIR = os.path.dirname(BASE_DIR)
BUNDLE_SRC_DIR = os.environ.get("BUNDLE_SRC_DIR", os.path.join(PARENT_DIR, "bundle"))
BUNDLE_TAR_PATH = os.environ.get("BUNDLE_TAR_PATH", os.path.join(BASE_DIR, "bundle.tar.gz"))

BOOTSTRAP_PORT = int(os.environ.get("BOOTSTRAP_PORT", "30105"))
HUB_PORT = int(os.environ.get("HUB_PORT", "30102"))
DEFAULT_HOST = os.environ.get("HUB_HOST", "")
PUBLIC_URL = os.environ.get("BOOTSTRAP_PUBLIC_URL", "").rstrip("/")

tar_lock = threading.Lock()


def _bundle_outdated():
    """True if any file under BUNDLE_SRC_DIR is newer than BUNDLE_TAR_PATH."""
    if not os.path.exists(BUNDLE_TAR_PATH):
        return True
    try:
        tar_mtime = os.path.getmtime(BUNDLE_TAR_PATH)
    except OSError:
        return True
    for root, _dirs, files in os.walk(BUNDLE_SRC_DIR):
        for name in files:
            p = os.path.join(root, name)
            try:
                if os.path.getmtime(p) > tar_mtime:
                    return True
            except OSError:
                continue
    return False


def ensure_bundle_tar():
    """Ensure bundle.tar.gz exists by packaging BUNDLE_SRC_DIR if missing or outdated."""
    with tar_lock:
        if os.path.exists(BUNDLE_TAR_PATH) and os.path.getsize(BUNDLE_TAR_PATH) > 0 \
                and not _bundle_outdated():
            return BUNDLE_TAR_PATH
        if not os.path.isdir(BUNDLE_SRC_DIR):
            return None
        print(f"[nt-bootstrap] Packaging bundle from {BUNDLE_SRC_DIR} -> {BUNDLE_TAR_PATH}...", flush=True)
        tmp_tar = BUNDLE_TAR_PATH + ".tmp"
        try:
            with tarfile.open(tmp_tar, "w:gz") as tar:
                # Exclude local caches from the deployment archive.
                for item in os.listdir(BUNDLE_SRC_DIR):
                    if item in ("__pycache__", ".git"):
                        continue
                    item_path = os.path.join(BUNDLE_SRC_DIR, item)
                    tar.add(item_path, arcname=item)
            os.replace(tmp_tar, BUNDLE_TAR_PATH)
            print(f"[nt-bootstrap] Created {BUNDLE_TAR_PATH} ({os.path.getsize(BUNDLE_TAR_PATH)} bytes)", flush=True)
            return BUNDLE_TAR_PATH
        except Exception as e:
            print(f"[nt-bootstrap] Error packaging bundle: {e}", file=sys.stderr, flush=True)
            if os.path.exists(tmp_tar):
                try:
                    os.remove(tmp_tar)
                except OSError:
                    pass
            return None


def _sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def generate_bootstrap_script(hub_host, bootstrap_port, hub_port, bootstrap_url=None, bundle_sha256=None):
    """Generate a 100% POSIX /bin/sh script to bootstrap the agent on remote nodes."""
    return f"""#!/bin/sh
# NetworkTracing remote agent bootstrap script (POSIX sh)
# Auto-generated by bootstrap server at port {bootstrap_port}
set -eu

BOOTSTRAP_HOST="{hub_host}"
BOOTSTRAP_PORT="{bootstrap_port}"
HUB_HOST="{hub_host}"
HUB_PORT="{hub_port}"

BOOTSTRAP_URL="{bootstrap_url or f'https://{hub_host}:{bootstrap_port}'}"
EXPECTED_SHA256="{bundle_sha256 or ''}"
HUB_ENDPOINT="http://${{HUB_HOST}}:${{HUB_PORT}}"

# Parse any custom arguments passed to bootstrap
EXTRA_ARGS=""
while [ $# -gt 0 ]; do
    case "$1" in
        --endpoint)
            HUB_ENDPOINT="${{2:?--endpoint requires a URL}}"
            shift 2
            ;;
        *)
            EXTRA_ARGS="$EXTRA_ARGS $1"
            shift
            ;;
    esac
done

log()  {{ echo "[nt-bootstrap] $*"; }}
warn() {{ echo "[nt-bootstrap] WARN: $*" >&2; }}
die()  {{ echo "[nt-bootstrap] FAIL: $*" >&2; exit 1; }}

[ "$(id -u)" = 0 ] || die "bootstrap must be run as root (or with sudo)"

TMPDIR=$(mktemp -d /tmp/nt-bootstrap.XXXXXX)
cleanup() {{
    rm -rf "$TMPDIR"
}}
trap cleanup EXIT INT TERM

log "NetworkTracing Agent Bootstrap"
log "Bootstrap source : $BOOTSTRAP_URL"
log "Target Hub endpoint: $HUB_ENDPOINT"
log "Temporary working dir: $TMPDIR"

# Download helper (curl or wget)
download_file() {{
    _url="$1"
    _dest="$2"
    if command -v curl >/dev/null 2>&1; then
        curl -sSfL "$_url" -o "$_dest"
    elif command -v wget >/dev/null 2>&1; then
        wget -qO "$_dest" "$_url"
    else
        die "Neither curl nor wget found on this system. Please install curl or wget."
    fi
}}

log "Downloading deployment bundle from $BOOTSTRAP_URL/bundle.tar.gz..."
download_file "$BOOTSTRAP_URL/bundle.tar.gz" "$TMPDIR/bundle.tar.gz" || die "Failed to download bundle archive"

[ -n "$EXPECTED_SHA256" ] || die "Bootstrap bundle digest is not configured"
if command -v sha256sum >/dev/null 2>&1; then
    printf '%s  %s\n' "$EXPECTED_SHA256" "$TMPDIR/bundle.tar.gz" | sha256sum -c - >/dev/null 2>&1 || die "Bundle SHA-256 verification failed"
elif command -v openssl >/dev/null 2>&1; then
    _actual=$(openssl dgst -sha256 "$TMPDIR/bundle.tar.gz" | sed 's/^.*= //')
    [ "$_actual" = "$EXPECTED_SHA256" ] || die "Bundle SHA-256 verification failed"
else
    die "sha256sum or openssl is required to authenticate the bundle"
fi

log "Extracting bundle..."
tar -xzf "$TMPDIR/bundle.tar.gz" -C "$TMPDIR" || die "Failed to extract bundle archive"

[ -f "$TMPDIR/install.sh" ] || die "Bundle is invalid: missing install.sh"

log "Executing installer in AGENT mode..."
# Pass target endpoint and any additional arguments
# shellcheck disable=SC2086
sh "$TMPDIR/install.sh" --endpoint "$HUB_ENDPOINT" $EXTRA_ARGS

case "$EXTRA_ARGS" in
    *--uninstall*)
        log "============================================================"
        log "NetworkTracing agent has been completely uninstalled."
        log "============================================================"
        ;;
    *--check*)
        ;;
    *)
        log "============================================================"
        log "Bootstrap complete! Agent is installed and shipping to $HUB_ENDPOINT"
        log "============================================================"
        ;;
esac
"""


