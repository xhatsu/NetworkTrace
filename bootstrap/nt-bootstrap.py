"""nt-bootstrap.py — Dedicated NetworkTracing bootstrap & bundle distribution server on port 30105.

Separated service:
- Serves POSIX bootstrap script on GET /bootstrap or /bootstrap.sh
- Serves complete deployment archive on GET /bundle.tar.gz
- Serves installer on GET /install.sh
- Serves health check on GET /healthz
- Agent simulator: background threads post realistic AGENT-STATS-PROTOCOL v1 samples to the hub
  every SIMULATE_INTERVAL seconds (default 30) for SIMULATE_AGENTS simulated nodes (default 3).
  Set SIMULATE_AGENTS=0 to disable. Set HUB_HOST / HUB_PORT to target a different hub.
- Default port: 30105 (configurable via BOOTSTRAP_PORT)
- Hub telemetry port: 30102 (configurable via HUB_PORT)
"""

